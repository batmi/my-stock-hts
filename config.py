# [추가] 로깅 설정 초기화 함수
def setup_logging():
    # 기존 핸들러 제거
    root = logging.getLogger()
    if root.handlers:
        for handler in root.handlers:
            root.removeHandler(handler)

    # 로깅 활성화
    logging.disable(logging.NOTSET)

    if not os.path.exists(LOG_DIR):
        try:
            os.makedirs(LOG_DIR)
        except Exception as e:
            print(f"[Config] LOG_DIR creation error: {e}")

    # [수정] 오래된 로그 파일 정리 (과거 패턴 및 핸들러 버그로 누적된 파일 강제 정리)
    try:
        if LOG_RETENTION_DAYS > 0:
            cutoff_date = datetime.now().date() - timedelta(days=LOG_RETENTION_DAYS)
            for filename in os.listdir(LOG_DIR):
                file_path = os.path.join(LOG_DIR, filename)
                
                try:
                    # 1. 기존 system_trade_YYYY-MM-DD.log 정리
                    if filename.startswith("system_trade_") and filename.endswith(".log"):
                        date_part = filename.replace("system_trade_", "").replace(".log", "")
                        file_date = datetime.strptime(date_part, "%Y-%m-%d").date()
                        if file_date < cutoff_date:
                            os.remove(file_path)
                    
                    # 2. 누적된 mystock_YYYYMMDD.log 및 autotrade_YYYYMMDD.log 강제 정리
                    elif (filename.startswith("mystock_") or filename.startswith("autotrade_")) and filename.endswith(".log"):
                        match = re.search(r'_(\d{8})\.log$', filename)
                        if match:
                            date_part = match.group(1)
                            file_date = datetime.strptime(date_part, "%Y%m%d").date()
                            if file_date < cutoff_date:
                                os.remove(file_path)
                except Exception as e:
                    print(f"[Config] Old log file remove error ({filename}): {e}")
    except Exception as e:
        print(f"[Config] Old log cleanup process error: {e}")

    log_filename = "mystock.log" # [수정] 고정 파일명 사용
    log_filepath = os.path.join(LOG_DIR, log_filename)

    # [수정] CustomTimedRotatingFileHandler 적용 (백업 파일 삭제 버그 수정)
    file_handler = CustomTimedRotatingFileHandler(
        log_filepath, when='midnight', interval=1, backupCount=LOG_RETENTION_DAYS, encoding='utf-8'
    )
    file_handler.suffix = "%Y%m%d"
    file_handler.namer = _log_namer

    # [수정] 로그 포맷에 파일명과 라인 번호 추가
    file_handler.setFormatter(logging.Formatter('%(asctime)s.%(msecs)03d [%(levelname)s] [%(threadName)s] %(filename)s:%(lineno)d - %(message)s', datefmt='%H:%M:%S'))
    
    # 파일 로그 레벨 설정
    level_name = settings.FILE_DEBUG_LEVEL.upper()
    numeric_level = getattr(logging, level_name, logging.INFO)

    logging.basicConfig(level=numeric_level, handlers=[file_handler], force=True)
    
    # [추가] 외부 라이브러리 로그 레벨 조정 (노이즈 감소)
    for lib in ["httpcore", "httpx", "urllib3", "google", "google.genai", "mistune", "markdown_it", "yfinance", "peewee"]:
        logging.getLogger(lib).setLevel(logging.WARNING)

    # [추가] 매매일지 웹서버 연동 로그는 FILE_DEBUG_LEVEL 과 무관하게 항상 INFO 이상을 남긴다.
    #  기본 파일 로그 레벨이 WARNING 이라 연동 시작·전송 완료 같은 '정상 동작' 기록이 통째로
    #  사라지는데, 외부 서버로 나가는 전송은 무엇이 언제 나갔는지 사후 추적이 되어야 한다.
    #  (자식 로거의 레벨만 낮추면 되고, 루트 핸들러는 레벨 필터가 없어 그대로 파일에 기록된다.
    #   FILE_DEBUG_LEVEL=DEBUG 로 더 자세히 보려는 경우는 그 설정을 존중한다.)
    logging.getLogger("modules.journal_sync").setLevel(min(numeric_level, logging.INFO))

    # [추가] 시스템 시작 표시는 FILE_DEBUG_LEVEL 과 무관하게 항상 남긴다.
    #  로그 파일은 하루 단위로만 나뉘어 한 파일에 여러 번의 실행이 섞인다. 어디서부터가
    #  이번 실행인지 가르는 기준선이 없으면 사후 추적이 사실상 불가능하다.
    #  (기본값 WARNING 에서는 이 한 줄마저 통째로 사라진다)
    logging.getLogger(STARTUP_LOGGER_NAME).setLevel(min(numeric_level, logging.INFO))

    # [추가] urllib3 커넥션 재시도 WARNING 억제.
    #  KIS 서버가 idle keep-alive 연결을 먼저 끊어(RemoteDisconnected) 발생하는
    #  "Retrying (Retry(total=...)) after connection broken by ..." 경고는 어댑터가
    #  자동 재시도로 자가 치유하는 정상 동작이라 로그 노이즈일 뿐이다.
    #  (특히 모의투자(2 TPS)는 요청 간격이 길어 연결이 오래 idle→더 빈번). ERROR로 올려 숨긴다.
    logging.getLogger("urllib3.connectionpool").setLevel(logging.ERROR)

    # [추가] 데이터 라이브러리의 '예상된 실패' ERROR를 DEBUG로 강등.
    #  야후 미제공 심볼(^K200FUT/^VKOSPI/^KQ150/^US02Y 등)의 404/"possibly delisted"와
    #  tvDatafeed 익명 웹소켓의 일시 끊김("Connection ... lost", "no data")은 자체 폴백·재시도로
    #  처리되는 설계상 정상 경로라 ERROR가 아니다. 핸들러 필터로 레벨을 낮춰(자식 로거 전파 포함)
    #  FILE_DEBUG_LEVEL=DEBUG일 때만 [DEBUG]로 기록한다. 우리 코드의 ERROR는 영향 없음.
    # [추가] 라이브러리의 '설계상 정상' WARNING도 강등 대상. (name, 메시지 조각) → 강등 레벨
    #  tvDatafeed 익명(nologin) 사용 경고는 우리가 의도적으로 선택한 접속 방식이라
    #  매 초기화마다 반복될 뿐 조치할 것이 없다 → INFO로 낮춘다.
    _DEMOTE_WARNINGS = (
        ("tvDatafeed", "you are using nologin method", logging.INFO),
    )

    class _DemoteExpectedLibErrors(logging.Filter):
        _NOISY = ("yfinance", "tvDatafeed", "websocket")

        @staticmethod
        def _is_lib(record, name):
            return record.name == name or record.name.startswith(name + ".")

        def filter(self, record):
            if record.levelno >= logging.ERROR and any(
                    self._is_lib(record, n) for n in self._NOISY):
                record.levelno = logging.DEBUG
                record.levelname = "DEBUG"
                return numeric_level <= logging.DEBUG

            if record.levelno == logging.WARNING:
                for lib_name, needle, target_level in _DEMOTE_WARNINGS:
                    if self._is_lib(record, lib_name) and needle in str(record.msg):
                        record.levelno = target_level
                        record.levelname = logging.getLevelName(target_level)
                        return numeric_level <= target_level
            return True

    file_handler.addFilter(_DemoteExpectedLibErrors())
        
    logging.info(f"=== 로깅 시스템 설정 갱신 (현재 파일 로그 레벨: {level_name}) ===")


