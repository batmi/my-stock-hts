    handler.namer = _log_namer
    
    # 메시지만 출력 (타임스탬프는 AutoTrader가 메시지에 포함해서 보냄)
    handler.setFormatter(logging.Formatter('%(message)s'))
    
    logger.addHandler(handler)
    return logger

